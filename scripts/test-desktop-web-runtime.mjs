import assert from "node:assert/strict";
import path from "node:path";
import runtime from "./desktop-web-runtime.cjs";

const { resolveDesktopWebMode, desktopWebPlan } = runtime;
assert.equal(resolveDesktopWebMode({ packaged: false }), "development");
assert.equal(resolveDesktopWebMode({ packaged: false, production: true }), "production");
assert.equal(resolveDesktopWebMode({ packaged: true }), "production");
assert.throws(() => resolveDesktopWebMode({ packaged: true, dev: true }), /installed_dev_refused/);
assert.throws(() => resolveDesktopWebMode({ packaged: false, dev: true, production: true }), /mode_conflict/);
const root = path.resolve("synthetic-source-root");
const options = { root, port: 4567, dataDir: path.join(root, "data"), env: { DATABASE_URL: "synthetic-db", YILING_ONEBOT_AUTOSTART: "1" } };
const dev = desktopWebPlan({ ...options, mode: "development" });
assert.equal(dev.env.NODE_ENV, "development");
assert.equal(dev.env.DATABASE_URL, "synthetic-db");
assert.equal(dev.env.YILING_ONEBOT_AUTOSTART, "0", "Nuxt must not start a second QQ stack");
assert.equal(dev.env.YILING_DESKTOP_IDENTITY_CONTROL, "0");
assert(dev.args.includes("--no-fork"), "managed dev server must stay in its guarded process");
assert(dev.args.includes("--no-open"));
assert(dev.args.includes("127.0.0.1"));
assert(!dev.args.some(arg => arg.includes(".output") || arg.includes("local-production-entry")));
const prod = desktopWebPlan({ ...options, mode: "production", identityControl: true });
assert.deepEqual(prod.args, [path.join(root, "scripts", "local-production-entry.mjs")]);
assert.equal(prod.env.NODE_ENV, "production");
assert.equal(prod.env.YILING_DESKTOP_IDENTITY_CONTROL, "1");
assert.equal(prod.env.YILING_SESSION_COOKIE, "yiling_session_desktop");
assert.throws(() => desktopWebPlan({ ...options, mode: "development", identityControl: true }), /installed_dev_refused/);
assert.throws(() => desktopWebPlan({ ...options, env: { YILING_DESKTOP_PACKAGED: "1" }, mode: "development" }), /installed_dev_refused/);
console.log("Desktop web modes passed: source dev, explicit production, installed identity isolation and single managed no-fork dev server.");
