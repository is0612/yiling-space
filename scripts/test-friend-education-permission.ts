import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { CHARACTER_BUNDLE_FORMAT, parseCharacterBundle } from "../server/utils/character-portable";
import { assertFriendEducationOwner, readFriendEducationPatch } from "../server/utils/friend-education-permission";
assert.equal(readFriendEducationPatch({}), undefined);
assert.equal(readFriendEducationPatch({ friendChatPolicy: "ALLOW", relationshipStage: "CLOSE_FRIEND" }), undefined);
assert.equal(readFriendEducationPatch({ educationEnabled: true }), true);
assert.equal(readFriendEducationPatch({ educationEnabled: false }), false);
for (const value of ["true", "false", 1, 0, null, [], {}]) assert.throws(() => readFriendEducationPatch({ educationEnabled: value }));
assert.equal(readFriendEducationPatch(Object.create({ educationEnabled: true })), undefined);
assert.doesNotThrow(() => assertFriendEducationOwner("owner", "owner"));
assert.throws(() => assertFriendEducationOwner("other-admin", "owner"));
const root = new URL("../", import.meta.url);
const file = (path: string) => readFileSync(new URL(path, root), "utf8");
const schema = file("prisma/schema.prisma");
const scope = schema.slice(schema.indexOf("model MemoryScope {"), schema.indexOf("model Conversation {"));
assert.match(scope, /educationEnabled\s+Boolean\s+@default\(false\)/);
const api = file("server/api/admin/identities/[id].patch.ts");
assert.match(api, /requireAdminActor\(event\)/);
assert.match(api, /assertFriendEducationOwner\(actor.user.id, scope.character.ownerId\)/);
assert.match(api, /friend.education_permission_updated/);
assert.match(api, /educationEnabled !== undefined \? \{ educationEnabled: result.relation.educationEnabled \}/);
const ui = file("app/components/SocialFriendsWorkspace.vue");
assert.match(ui, /允许教育此角色/);
assert.match(ui, /仅影响新教育候选；关闭不会撤销已采纳的习惯/);
const transfer = file("server/utils/character-transfer.ts");
assert(!transfer.includes("educationEnabled"), "import cannot inherit an external card's education permission");
const imported = parseCharacterBundle({ format: CHARACTER_BUNDLE_FORMAT, formatVersion: 1, character: { name: "测试角色", basePrompt: "测试" }, friends: [{ platform: "qq-onebot", platformUid: "123", educationEnabled: true }] });
assert.equal(Object.prototype.hasOwnProperty.call(imported.friends[0], "educationEnabled"), false, "untrusted import field is not accepted");
console.log("Friend education permission: strict boolean, explicit owner, default deny, API/UI contract and import whitelist passed (no database).");
