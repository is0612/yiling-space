#!/usr/bin/env node
/**
 * 安装（或更新）本地 git 钩子：提交前跑 check:privacy。
 *
 * 为什么不在 `postinstall` 里自动装：安装钩子等于替用户改变 git 行为，
 * 有人在同一个仓库里同时跑别的工具链，被莫名拦下很难查。装不装由人决定，
 * 装的时候也知道自己在装什么。
 *
 * 用法：
 *   node scripts/install-git-hooks.mjs           # 安装
 *   node scripts/install-git-hooks.mjs --remove  # 卸载（只删本脚本生成的）
 */
import { execFileSync } from "node:child_process";
import { chmodSync, existsSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const MARKER = "# generated by scripts/install-git-hooks.mjs";

const HOOK = `#!/bin/sh
${MARKER}
# 提交前跑隐私门禁。删掉本文件或 yarn check:hooks --remove 可卸载。
yarn --silent run check:privacy || {
  echo ""
  echo "提交被拦下：上面的内容不该进这个公开仓库（github.com/is0612/yiling-space）。"
  echo "误报 → 往 scripts/privacy-allowlist.txt 加一行（只限伪造/公开数据）。"
  echo "如果拦的是一批跟本次提交无关的旧内容，那是待清理的旧账，不是你的改动引入的。"
  echo "真要绕过 → git commit --no-verify，但请先确认那不是真实号码或昵称。"
  exit 1
}
`;

const ROOT = resolve(process.cwd());
let gitDir;
try {
  gitDir = execFileSync("git", ["rev-parse", "--git-dir"], { cwd: ROOT, encoding: "utf8" }).trim();
} catch {
  console.error("check:hooks —— 当前目录不是 git 仓库，跳过。");
  process.exit(1);
}

const hookPath = join(ROOT, gitDir, "hooks", "pre-commit");
const remove = process.argv.includes("--remove");

if (remove) {
  if (!existsSync(hookPath)) {
    console.log("check:hooks —— 没有已安装的 pre-commit。");
    process.exit(0);
  }
  if (!readFileSync(hookPath, "utf8").includes(MARKER)) {
    console.error("check:hooks —— 该 pre-commit 不是本脚本生成的，不动它。");
    process.exit(1);
  }
  unlinkSync(hookPath);
  console.log("check:hooks —— 已卸载 pre-commit。");
  process.exit(0);
}

if (existsSync(hookPath) && !readFileSync(hookPath, "utf8").includes(MARKER)) {
  console.error(
    `check:hooks —— ${hookPath} 已存在且不是本脚本生成的。\n`
    + "为免覆盖你自己的钩子，这里不写。请手动把下面一行加进去：\n"
    + "  yarn --silent run check:privacy",
  );
  process.exit(1);
}

writeFileSync(hookPath, HOOK, "utf8");
chmodSync(hookPath, 0o755);
console.log(`check:hooks —— 已安装 ${hookPath}`);
console.log("提交时会先跑 check:privacy；跨平台注意：Windows 的 Git Bash 也能执行。");
