import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createContext, Script } from "node:vm";
import ts from "typescript";

const source = readFileSync(new URL("../app/components/ModelTurnDetail.vue", import.meta.url), "utf8");
const setup = source.match(/<script setup lang="ts">([\s\S]*?)<\/script>/)?.[1];
assert(setup);
const parsed = ts.createSourceFile("component.ts", setup, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
const body = parsed.statements.filter(statement => !ts.isImportDeclaration(statement)).map(statement => statement.getText(parsed)).join("\n");
const script = ts.transpileModule(`(function(){${body};return {growthReads,growthDomains,growthReadStatuses,growthReferenceLabel,growthVersion,shortId};})()`, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.None } }).outputText;
const props: { result: { detail: { growthReads?: unknown } } } = { result: { detail: {} } };
const bindings = new Script(script).runInContext(createContext({ defineProps: () => props, computed: (get: () => unknown) => Object.defineProperty({}, "value", { get }), Intl })) as {
  growthReads: { value: unknown };
  growthDomains: Record<string, string>; growthReadStatuses: Record<string, string>;
  growthReferenceLabel(read: { domain: string; usedIds: string[] }): string;
  growthVersion(item: { id: string; revision?: number; updatedAt?: string }): string;
  shortId(value: string): string;
};
assert.equal(bindings.growthReads.value, undefined, "Legacy absence must not fabricate zero-count records");
props.result.detail.growthReads = [];
assert.equal((bindings.growthReads.value as unknown[]).length, 0, "Recorded empty list differs from absent diagnostics");
assert.deepEqual(Object.keys(bindings.growthDomains).sort(), ["goals", "knowledge", "language", "preferences"]);
assert.equal(bindings.growthDomains.goals, "愿望"); assert.equal(bindings.growthDomains.language, "语言习惯");
for (const status of ["not_needed", "no_match", "failed", "budget_excluded", "provided"]) assert(bindings.growthReadStatuses[status]);
assert.equal(bindings.growthReferenceLabel({ domain: "knowledge", usedIds: [] }), "知识暂未回传引用");
assert.equal(bindings.growthReferenceLabel({ domain: "knowledge", usedIds: ["unexpected"] }), "知识暂未回传引用", "No unsupported knowledge citation count may be claimed");
assert.equal(bindings.growthReferenceLabel({ domain: "preferences", usedIds: ["one", "two"] }), "模型自报引用 2 条");
assert.match(bindings.growthReferenceLabel({ domain: "language", usedIds: [] }), /不代表未受影响/);
assert.equal(bindings.growthVersion({ id: "one", revision: 2 }), "版本 2");
assert.match(bindings.growthVersion({ id: "one", updatedAt: "2026-11-11T00:00:00Z" }), /更新时间/);
assert.equal(bindings.growthVersion({ id: "one" }), "未保存版本标记");
assert.equal(bindings.shortId("123456789012345678901234"), "12345678…1234");
const row = { domain: "goals", status: "provided", candidateCount: 10, matchedCount: 7, selectedCount: 2, budgetExcludedCount: 3, limitExcludedCount: 2, candidateLimitReached: true, provided: [{ id: "goal-a", revision: 4 }], usedIds: ["goal-a"] };
props.result.detail.growthReads = [row];
assert.equal((bindings.growthReads.value as typeof row[])[0]!.selectedCount, 2);
for (const text of ["成长数据读取与引用", "候选", "匹配", "选入", "预算未选入", "条数上限未选入", "仅本次有限候选，不代表全库", "模型自报引用也不证明实际影响", "旧记录未保存成长数据读取诊断", "不据此判断没有读取或引用", "已选入的条目与版本", "本次候选读取已达上限", "本轮消息", "语境理解", "记忆检索", "助手协作诊断", "回应结果"]) assert(source.includes(text), text);
assert(source.includes('v-if="growthReads"')); assert(source.includes("read.candidateLimitReached"));
assert(source.includes("shortId(item.id)")); assert(source.includes("growthVersion(item)"));
assert(source.includes("read.domain !== 'knowledge' && read.usedIds.length"));
const section = source.slice(source.indexOf('<section class="turn-section growth-read-section">'), source.indexOf('<h3>回应结果</h3>'));
assert(!section.includes("item.content")); assert(!section.includes("item.reason")); assert(!section.includes("item.title"));
assert(!source.includes("v-html")); assert(!/font-size:\s*(?:[0-9]|1[01])px/.test(source));
console.log("Growth read diagnostics UI: legacy absence, bounded candidate counts, domain/status labels, version references, unsupported knowledge citations and existing sections passed (script-level, no DOM).");
