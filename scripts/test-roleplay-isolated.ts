import "dotenv/config";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { spawnSync } from "node:child_process";
import { Client } from "pg";
import { getPrisma } from "../server/utils/prisma";
import { testRoleplayChannelDatabase } from "./test-roleplay-channel";
import { testRoleplayGroupDatabase } from "./test-roleplay-group";
import * as service from "../server/utils/roleplay-service";
import { contextMessages, contextCost, validateSettings } from "../server/utils/roleplay-context";

const source = new URL(process.env.DATABASE_URL!);
assert(["localhost", "127.0.0.1", "[::1]"].includes(source.hostname));
source.pathname = "/postgres";
const name = `yiling_roleplay_test_${randomUUID().replaceAll("-", "")}`;
assert(/^yiling_roleplay_test_[a-f0-9]{32}$/.test(name));
const target = new URL(source); target.pathname = `/${name}`;
const admin = new Client({ connectionString: source.toString() });
await admin.connect();
let created = false;
const original = globalThis.fetch;
const requestIds = new Map<string, string>();
const request = (name: string) => { if (!requestIds.has(name)) requestIds.set(name, randomUUID()); return requestIds.get(name)!; };
try {
  await admin.query(`CREATE DATABASE "${name}"`); created = true;
  process.env.DATABASE_URL = target.toString();
  assert.equal(spawnSync(process.execPath, ["node_modules/prisma/build/index.js", "migrate", "deploy"], { env: process.env, stdio: "inherit" }).status, 0);
  const db = getPrisma();
  try {
    const owner = await db.user.create({ data: { username: randomUUID(), passwordHash: "not-login" } });
    const stranger = randomUUID();
    const host = await db.character.create({ data: { ownerId: owner.id, name: "Test host", basePrompt: "Host identity must not leak" } });
    const settings = await service.updateSettings(owner.id, { apiKey: "mock-only-secret", apiBaseUrl: "http://127.0.0.1:4567/v1", model: "mock", thinking: false, recentMessageLimit: 4 });
    await testRoleplayChannelDatabase(db, owner.id, host.id);
    await testRoleplayGroupDatabase(db, owner.id, host.id);
    assert(settings.hasApiKey); assert(!JSON.stringify(settings).includes("mock-only-secret"));
    assert.match((await db.roleplaySetting.findUniqueOrThrow({ where: { ownerId: owner.id } })).apiKeyCiphertext!, /^v1\./);
    const persona = await service.createPersona(owner.id, { name: "测试角色", prompt: "You are a fictional conversational companion.", opening: "Hello" });
    const session = await service.createRoleplaySession(owner.id, { personaId: persona.id });
    const second = await service.createRoleplaySession(owner.id, { personaId: persona.id });
    assert.deepEqual(await service.listPersonas(stranger), []);
    await assert.rejects(service.getRoleplaySession(stranger, session.id));
    await assert.rejects(service.createRoleplaySession(stranger, { personaId: persona.id }));
    let calls = 0; let fail = false; let invalidSummary = false;
    const payloads: Record<string, unknown>[] = [];
    globalThis.fetch = async (_url, init) => {
      calls++;
      const payload = JSON.parse(String(init?.body)); payloads.push(payload);
      if (fail) return new Response("", { status: 503 });
      const summary = payload.response_format?.type === "json_object";
      let content = "Mock answer";
      if (summary) {
        assert.deepEqual(payload.messages.map((m: { role: string }) => m.role), ["system", "user"]);
        const source = JSON.parse(payload.messages[1].content);
        assert(Array.isArray(source.transcript));
        assert(!payload.messages[0].content.includes("Name: 测试角色"));
        content = invalidSummary ? "（继续演出下一句，而不是总结）" : JSON.stringify({ facts: ["双方进行了问候。"], openThreads: [], currentState: ["对话尚未结束。"], coveredThrough: source.throughSequence });
      }
      return new Response(JSON.stringify({ choices: [{ message: { content }, finish_reason: "stop" }], usage: { prompt_tokens: 20, completion_tokens: 5, total_tokens: 25 } }));
    };
    const a = await service.sendMessage(owner.id, session.id, { content: "Hi", requestId: request("a") });
    assert.equal(a.replayed, false);
    const before = calls;
    assert((await service.sendMessage(owner.id, session.id, { content: "Hi", requestId: request("a") })).replayed);
    assert.equal(calls, before);
    await assert.rejects(service.sendMessage(owner.id, session.id, { content: "Changed", requestId: request("a") }));
    assert.equal((await service.getRoleplaySession(owner.id, second.id)).messages.length, 1);
    assert.deepEqual((payloads[0]!.messages as { role: string }[]).map(m => m.role), ["system", "assistant", "user"]);
    assert(JSON.stringify(payloads[0]).includes("Name: 测试角色"));
    assert(!JSON.stringify(payloads).includes("memories")); assert(!JSON.stringify(payloads).includes("tools"));
    fail = true;
    await assert.rejects(service.sendMessage(owner.id, session.id, { content: "Retry me", requestId: request("b") }));
    assert.equal((await service.getRoleplaySession(owner.id, session.id)).messages.filter(m => m.requestId === request("b")).length, 1);
    await assert.rejects(service.sendMessage(owner.id, session.id, { content: "Do not skip", requestId: request("c") }));
    fail = false;
    await service.sendMessage(owner.id, session.id, { content: "Retry me", requestId: request("b") });
    assert.equal((await service.getRoleplaySession(owner.id, session.id)).messages.filter(m => m.requestId === request("b")).length, 2);
    const countBefore = await db.roleplayMessage.count({ where: { sessionId: session.id } });
    const compressed = await service.compressSession(owner.id, session.id);
    assert(compressed.summaryThrough > 0);
    assert.equal(await db.roleplayMessage.count({ where: { sessionId: session.id } }), countBefore);
    assert.match(compressed.summary, /【已发生与关系】/u);
    const savedThrough = compressed.summaryThrough;
    invalidSummary = true;
    await assert.rejects(service.compressSession(owner.id, session.id, { rebuild: true }));
    assert.equal((await service.getRoleplaySession(owner.id, session.id)).summary, compressed.summary);
    assert.equal((await service.getRoleplaySession(owner.id, session.id)).summaryThrough, savedThrough);
    invalidSummary = false;
    await db.roleplaySession.update({ where: { id: session.id }, data: { summary: "旧的错误续聊文本" } });
    const rebuilt = await service.compressSession(owner.id, session.id, { rebuild: true });
    const rebuildSource = JSON.parse((payloads.at(-1)!.messages as { content: string }[])[1]!.content);
    assert.equal(rebuildSource.previousSummary, "");
    assert.equal(rebuildSource.transcript[0].sequence, 1);
    assert(!rebuilt.summary.includes("错误续聊"));
    assert.equal(await db.roleplayMessage.count({ where: { sessionId: session.id } }), countBefore);
    await service.updatePersona(owner.id, persona.id, { prompt: "Updated persona" });
    assert.notEqual(((await service.getRoleplaySession(owner.id, session.id)).personaSnapshot as { prompt: string }).prompt, "Updated persona");
    await service.applyPersona(owner.id, session.id);
    assert.equal((await service.getRoleplaySession(owner.id, session.id)).personaSnapshot.prompt, "Updated persona");
    await db.roleplaySession.update({ where: { id: session.id }, data: { leaseToken: randomUUID(), leaseUntil: new Date(Date.now() + 60000) } });
    await assert.rejects(service.sendMessage(owner.id, session.id, { content: "Locked", requestId: request("lock") }));
    await db.roleplaySession.update({ where: { id: session.id }, data: { leaseUntil: new Date(0) } });
    await service.sendMessage(owner.id, session.id, { content: "Recovered lease", requestId: request("recovered") });
    const summaryBeforeFailure = (await service.getRoleplaySession(owner.id, session.id)).summary;
    fail = true;
    await assert.rejects(service.compressSession(owner.id, session.id));
    fail = false;
    assert.equal((await service.getRoleplaySession(owner.id, session.id)).summary, summaryBeforeFailure);
    await service.updateSettings(owner.id, { contextBudgetTokens: 800, maxTokens: 256, contextWindowTokens: 4096 });
    const longPersona = await service.createPersona(owner.id, { name: "Budget test", prompt: "x".repeat(1000), opening: "" });
    const longSession = await service.createRoleplaySession(owner.id, { personaId: longPersona.id });
    const budgetCalls = calls;
    await assert.rejects(service.sendMessage(owner.id, longSession.id, { content: "hello", requestId: randomUUID() }));
    assert.equal(calls, budgetCalls);
    assert.equal((await service.getRoleplaySession(owner.id, longSession.id)).messages.length, 1);
    await service.deletePersona(owner.id, persona.id);
    assert.equal((await service.getRoleplaySession(owner.id, session.id)).personaId, null);
    assert((await service.getRoleplaySession(owner.id, session.id)).messages.length > 1);
    assert((await db.modelUsage.count({ where: { userId: owner.id, kind: "roleplay-chat" } })) > 0);
    assert(contextCost(contextMessages("a", "", [{ role: "user", sequence: 1, content: "中" }])) > 0);
    assert.throws(() => validateSettings({ contextWindowTokens: 100, maxTokens: 100, contextBudgetTokens: 100 }));
    assert.throws(() => validateSettings({ recentMessageLimit: 1 }));
    assert.equal(validateSettings({ recentMessageLimit: 2 }).recentMessageLimit, 2);
    await service.deleteSession(owner.id, second.id);
    assert.equal(await db.roleplayMessage.count({ where: { sessionId: second.id } }), 0);
    await service.updateSettings(owner.id, { clearApiKey: true });
    assert.equal((await service.getSettings(owner.id)).hasApiKey, false);
    console.log("Roleplay isolated tests passed: migration, encrypted settings, owner/session isolation, native messages, persona snapshot, durable failure retry, dedupe, lease recovery, compression preserves originals, usage, budget.");
  } finally { await db.$disconnect(); }
} finally {
  globalThis.fetch = original;
  if (created) await admin.query(`DROP DATABASE "${name}" WITH (FORCE)`);
  await admin.end();
}
