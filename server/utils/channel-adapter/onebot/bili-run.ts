/**
 * 群聊里的「去刷一轮 B站」指令识别。
 *
 * 只做文本判定，不碰 B站 流程：真正的执行仍走 `bili/duty-pipeline.ts` 的
 * `runDutyRound`，额度、模型、bili CLI 都与值班台手动跑一轮完全一致。
 */

/**
 * 「刷B站」要成为指令，必须是「请你去做这个动作」的祈使句，
 * 而不是「提到刷B站这件事」—— 否则群里说一句
 * 「帮你优化了刷B站的功能」也会被当成叫她去刷一轮。
 *
 * 判定思路：指令句里「刷/跑/逛/看」是真正的谓语动词（祈使），
 * 而误触句里它前面另有动词在做谓语（优化、添加、修……），
 * 「刷B站」只是那个动词的宾语（刷B站这个功能 / 这个 bug）。
 */
export function isBiliRunCommand(content: string): boolean {
  // @QQ号 不算内容；统一小写后同时认 B站 / bilibili。
  const text = content.replace(/@\d+/gu, "").replace(/\s+/g, "").toLowerCase();
  if (!text) return false;

  // 「刷B站」这类动作短语：刷B站 / 跑一轮b站 / 逛一圈bilibili / B站刷一轮 …
  const action = /(?:刷|跑|逛|看)(?:一|1)?(?:轮|圈|下)?(?:b站|bilibili)|(?:b站|bilibili)(?:刷|跑|逛|看)(?:一|1)?(?:轮|圈|下)?/u;

  // 没有「刷B站」字样，肯定不是。
  if (!action.test(text)) return false;

  // 否定句：别刷B站 / 不要跑B站 / 不用逛了。
  if (/(别|不要|不用|停止|取消|别再|不用再|别去|不用去).{0,4}(刷|跑|逛|看)/u.test(text)) return false;

  // 完成态陈述：我刷B站了 / 今天刷过了 —— 说的是「已经做过了」，不是叫她去。
  // 完成态的标志是「刷/跑/逛/看」后面紧跟「了/过」，而指令祈使句没有这个。
  if (/(?:刷|跑|逛|看)(?:一|1)?(?:轮|圈|下)?(?:b站|bilibili)(?:了|过)/u.test(text)) {
    if (!/(?:去|帮我|请你|麻烦|让|叫|给我|来)(?:你|我)?/u.test(text)) return false;
  }

  // 陈述句：另有动词做谓语，「刷B站」是它的宾语。
  //   · 「帮你优化了刷B站的功能」→ 谓语是「优化了」
  //   · 「我把刷B站的功能改好了」→ 谓语是「改好」
  //   · 「刷B站的功能坏了」→ 谓语是「坏」
  // 关键是：这个别的动词必须出现在「刷B站」之前，且句子里没有祈使引导词。
  if (/(优化|添加|增加|修改|改|修|做|写|实现|完成|弄|整理|调整|更新|部署|上线|测试|讨论|聊|讲解|坏了|好了|加了|改了|修了)(?:了|完|好|一下|好了|完了|过了)?/u.test(text)) {
    // 但「帮我优化刷B站的逻辑，然后刷一轮」这类带祈使引导的，仍要认指令。
    if (!/(?:去|帮我|请你|麻烦|让|叫|给我|来)(?:你|我)?/u.test(text)) return false;
  }

  return true;
}
